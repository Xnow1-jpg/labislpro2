import math


def area(r):
    '''Принимает число r, r - радиус круга, функция возвращает площадь круга, math.pi - это значение числа пи'''
    return math.pi * r * r


def perimeter(r):
    '''Принимает число r, r - радиус круга, функция возвращает длину окружности круга, math.pi - это значение числа пи'''
    return 2 * math.pi * r

